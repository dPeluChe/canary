// deps.Supported advertises five lockfile kinds. Only package-lock.json had
// ever been proven transitively complete; the other four were a promise with
// no evidence behind them. An extractor that quietly returned only declared
// dependencies for yarn or pnpm would reproduce the exact defect that made the
// reference project useless, and every negative from it would be worthless.
//
// Each fixture below declares a handful of packages in package.json and
// resolves hundreds in the lockfile, with keyv@6.0.0 present ONLY as a
// transitive — never in the manifest, exactly where the real one was.

const (
	fmtDeclared = 8
	fmtResolved = 300
)

func buildYarnLock() string {
	var b strings.Builder
	b.WriteString("# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n")
	for i := 0; i < fmtResolved; i++ {
		fmt.Fprintf(&b, "dep-%04d@^1.0.0:\n  version \"1.0.%d\"\n  resolved \"https://registry.yarnpkg.com/dep-%04d/-/dep-%04d-1.0.%d.tgz\"\n\n", i, i, i, i, i)
	}
	b.WriteString("keyv@^6.0.0:\n  version \"6.0.0\"\n  resolved \"https://registry.yarnpkg.com/keyv/-/keyv-6.0.0.tgz\"\n")
	return b.String()
}

func buildPnpmLock() string {
	var b strings.Builder
	b.WriteString("lockfileVersion: 5.3\n\nspecifiers:\n")
	for i := 0; i < fmtDeclared; i++ {
		fmt.Fprintf(&b, "  dep-%04d: ^1.0.0\n", i)
	}
	b.WriteString("\ndependencies:\n")
	for i := 0; i < fmtDeclared; i++ {
		fmt.Fprintf(&b, "  dep-%04d: 1.0.%d\n", i, i)
	}
	b.WriteString("\npackages:\n\n")
	for i := 0; i < fmtResolved; i++ {
		fmt.Fprintf(&b, "  /dep-%04d/1.0.%d:\n    resolution: {integrity: sha512-x}\n    dev: false\n\n", i, i)
	}
	b.WriteString("  /keyv/6.0.0:\n    resolution: {integrity: sha512-y}\n    dev: false\n")
	return b.String()
}

func buildBunLock() string {
	direct := map[string]string{}
	packages := map[string]any{}
	for i := 0; i < fmtResolved; i++ {
		name := fmt.Sprintf("dep-%04d", i)
		packages[name] = []any{fmt.Sprintf("%s@1.0.%d", name, i), map[string]any{}, "h" + name}
		if i < fmtDeclared {
			direct[name] = "^1.0.0"
		}
	}
	packages["keyv"] = []any{"keyv@6.0.0", map[string]any{}, "hkeyv"}

	b, err := json.Marshal(map[string]any{
		"lockfileVersion": 0,
		"workspaces":      map[string]any{"": map[string]any{"dependencies": direct}},
		"packages":        packages,
	})
	if err != nil {
		panic(err)
	}
	return string(b)
}

func buildPackageLock() string {
	direct := map[string]string{}
	packages := map[string]any{}
	for i := 0; i < fmtResolved; i++ {
		name := fmt.Sprintf("dep-%04d", i)
		packages["node_modules/"+name] = map[string]any{"version": fmt.Sprintf("1.0.%d", i)}
		if i < fmtDeclared {
			direct[name] = "^1.0.0"
		}
	}
	packages["node_modules/dep-0000/node_modules/keyv"] = map[string]any{"version": "6.0.0"}
	packages[""] = map[string]any{"name": "app", "dependencies": direct}

	b, err := json.Marshal(map[string]any{
		"name": "app", "lockfileVersion": 3, "packages": packages,
	})
	if err != nil {
		panic(err)
	}
	return string(b)
}

// TestExtractIsTransitivelyCompleteForEverySupportedFormat closes the gap an
// audit named: deps.Supported promises five kinds and only one was proven.
func TestExtractIsTransitivelyCompleteForEverySupportedFormat(t *testing.T) {
	formats := []struct {
		kind  string
		build func() string
	}{
		{"package-lock.json", buildPackageLock},
		{"npm-shrinkwrap.json", buildPackageLock},
		{"yarn.lock", buildYarnLock},
		{"pnpm-lock.yaml", buildPnpmLock},
		{"bun.lock", buildBunLock},
	}

	for _, f := range formats {
		t.Run(f.kind, func(t *testing.T) {
			dir := t.TempDir()

			// The manifest declares a handful. Anything reading it instead of
			// the lockfile answers a different question.
			declared := map[string]string{}
			for i := 0; i < fmtDeclared; i++ {
				declared[fmt.Sprintf("dep-%04d", i)] = "^1.0.0"
			}
			manifest, err := json.Marshal(map[string]any{"name": "app", "dependencies": declared})
			if err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(dir, "package.json"), manifest, 0o644); err != nil {
				t.Fatal(err)
			}

			path := filepath.Join(dir, f.kind)
			if err := os.WriteFile(path, []byte(f.build()), 0o644); err != nil {
				t.Fatal(err)
			}

			got, err := Extract(discover.Lockfile{Path: path, Kind: f.kind, Ecosystem: "npm"})
			if err != nil {
				t.Fatalf("%s: %v", f.kind, err)
			}

			if len(got) <= fmtDeclared*2 {
				t.Fatalf("%s resolved %d package(s) against %d declared — this reads like manifest parsing, which is the defect that killed the reference project",
					f.kind, len(got), fmtDeclared)
			}

			// The package that matters: transitive, absent from package.json.
			var found bool
			for _, r := range got {
				if r.Name == "keyv" && r.Version == "6.0.0" {
					found = true
					break
				}
			}
			if !found {
				t.Fatalf("%s did not resolve keyv@6.0.0, which is present in the lockfile and absent from the manifest — a negative from this extractor would be worthless", f.kind)
			}
			t.Logf("%s: %d resolved against %d declared", f.kind, len(got), fmtDeclared)
		})
	}
}

// Supported must not advertise a kind Extract cannot read, and must not refuse
// one it can: either way the report would be wrong about its own coverage.
func TestSupportedMatchesWhatExtractCanActuallyRead(t *testing.T) {
	readable := map[string]func() string{
		"package-lock.json":   buildPackageLock,
		"npm-shrinkwrap.json": buildPackageLock,
		"yarn.lock":           buildYarnLock,
		"pnpm-lock.yaml":      buildPnpmLock,
		"bun.lock":            buildBunLock,
	}
	for kind, build := range readable {
		if !Supported(kind) {
			t.Errorf("%s is readable but Supported says otherwise", kind)
			continue
		}
		dir := t.TempDir()
		path := filepath.Join(dir, kind)
		if err := os.WriteFile(path, []byte(build()), 0o644); err != nil {
			t.Fatal(err)
		}
		if _, err := Extract(discover.Lockfile{Path: path, Kind: kind, Ecosystem: "npm"}); err != nil {
			t.Errorf("Supported(%q) is true but Extract failed: %v", kind, err)
		}
	}

	// bun.lockb is binary and discover finds it, but no extractor reads it.
	// Claiming support would turn an unread file into a clean answer.
	for _, kind := range []string{"bun.lockb", "Cargo.lock", "go.sum", "requirements.txt", "Gemfile.lock"} {
		if Supported(kind) {
			t.Errorf("%s has no extractor and must not be advertised as supported", kind)
		}
	}
}
